"""Collect every translatable string in Nyte Lyte's Paladin Toolkit.

Keys are the English text inside L["..."] in the addon's Lua files, plus
EXTRA: words the code passes through L[...] at runtime (spec detection,
import errors, why addon messages are blocked, class names).

  python tools/locale_keys.py           rewrite Locales/_template.lua
  python tools/locale_keys.py --check   exit 1 if the template is stale

To translate: copy Locales/_template.lua to Locales/<code>.lua (deDE, frFR,
esES, esMX, ptBR, ruRU, itIT, koKR, zhCN, zhTW), set the code on the
NewLocale line, translate the right-hand sides, delete the lines you skip
(English is used for those), and list the file in the TOC with the other
Locales files.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = os.path.join(ROOT, "Locales", "_template.lua")
SKIP_DIRS = {"tests", "tools", "Locales", "private", "docs", "dist", ".git"}
KEY = re.compile(r'\bL\["((?:[^"\\]|\\.)*)"\]')

# Translated at runtime with L[value]; the extractor can't see these.
EXTRA = {
    "Core/SpecProfile.lua (detection)": [
        "high", "low", "manual", "talent points", "known spells", "could not detect", "chosen by you",
    ],
    "Logic/Serializer.lua (import errors)": [
        "nothing to import",
        "that isn't a Paladin Toolkit export string",
        "that string is from a newer version of the addon",
        "the string is damaged (invalid characters)",
        "the string is incomplete or was changed (checksum mismatch)",
        "the string is damaged (extra data)",
        "the string doesn't contain a profile",
    ],
    "Services/Comm.lua (why sending is blocked)": [
        "boss encounter", "not in a group", "in combat", "chat messaging lockdown",
    ],
    "Class names (only used if the game doesn't provide them)": [
        "Warrior", "Paladin", "Hunter", "Rogue", "Priest", "Shaman", "Mage", "Warlock", "Druid",
    ],
}


def lua_files():
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        for f in sorted(files):
            if f.endswith(".lua"):
                yield os.path.join(d, f)


def collect():
    keys = {}
    for path in lua_files():
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        src = open(path, encoding="utf-8").read()
        for m in KEY.finditer(src):
            keys.setdefault(m.group(1), rel)
    for where, words in EXTRA.items():
        for w in words:
            keys.setdefault(w, where)
    return keys


def render(keys):
    out = [
        "-- Nyte Lyte's Paladin Toolkit translation template",
        "-- (generated by tools/locale_keys.py; do not edit this file).",
        "-- Copy it to Locales/<code>.lua, set the code below, translate the right-hand",
        "-- sides, and list the file in the TOC next to the other Locales files.",
        "-- Keep %s / %d placeholders in the same order, and keep |cff...|r color codes",
        "-- and /ptk commands as they are. Lines you delete stay in English.",
        "local _, PK = ...",
        'local L = PK.NewLocale("xxXX")',
        "if not L then",
        "\treturn",
        "end",
        "",
    ]
    by_file = {}
    for k, f in keys.items():
        by_file.setdefault(f, []).append(k)
    for f in sorted(by_file):
        out.append("-- " + f)
        for k in sorted(by_file[f], key=str.lower):
            out.append('L["%s"] = "%s"' % (k, k))
        out.append("")
    return "\n".join(out)


def main():
    keys = collect()
    text = render(keys)
    if "--check" in sys.argv:
        cur = open(TEMPLATE, encoding="utf-8").read() if os.path.exists(TEMPLATE) else ""
        if cur.replace("\r\n", "\n") != text:
            print("Locales/_template.lua is stale: run python tools/locale_keys.py")
            return 1
        print("locale template up to date (%d keys)" % len(keys))
        return 0
    os.makedirs(os.path.dirname(TEMPLATE), exist_ok=True)
    open(TEMPLATE, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %d keys to Locales/_template.lua" % len(keys))
    return 0


if __name__ == "__main__":
    sys.exit(main())
